package com.example.service

import android.app.Notification
import android.content.ComponentName
import android.content.Context
import android.os.Build
import android.os.PowerManager
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import com.example.data.model.EventLogItem
import com.example.data.model.LogEventType
import com.example.data.repository.AppLogRepository
import com.example.data.repository.ConfigRepository
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch

class SFRNotificationListenerService : NotificationListenerService() {

    private val serviceScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private var wakeLock: PowerManager.WakeLock? = null

    override fun onCreate() {
        super.onCreate()
        try {
            val pm = getSystemService(Context.POWER_SERVICE) as PowerManager
            wakeLock = pm.newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "SFRDroid:ListenerWakeLock")
        } catch (_: Exception) {}
    }

    override fun onListenerConnected() {
        super.onListenerConnected()
        AppLogRepository.getInstance().addLog(
            EventLogItem(
                type = LogEventType.SYSTEM_EVENT,
                title = "Akses Notifikasi Terhubung",
                details = "SFR Droid Listener siap menangkap & meneruskan notifikasi secara real-time.",
                success = true
            )
        )
    }

    override fun onListenerDisconnected() {
        super.onListenerDisconnected()
        AppLogRepository.getInstance().addLog(
            EventLogItem(
                type = LogEventType.SYSTEM_EVENT,
                title = "Akses Notifikasi Terputus (Menyambung Ulang...)",
                details = "Mencoba menyambungkan kembali listener notifikasi ke sistem Android...",
                success = false
            )
        )
        try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N) {
                requestRebind(ComponentName(this, SFRNotificationListenerService::class.java))
            }
        } catch (_: Exception) {}
    }

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        super.onNotificationPosted(sbn)
        if (sbn == null) return

        val pkg = sbn.packageName ?: return

        // Ignore notifications generated by SFR Droid itself to prevent infinite loops
        if (pkg == packageName) return

        val configRepo = ConfigRepository.getInstance(applicationContext)
        val config = configRepo.getConfig()

        // Verify standby is active
        if (!config.isStandby) return

        // Verify package is allowed (if forwardAllApps is enabled OR if selectedApps contains package, or if selectedApps is empty, allow all by default)
        val isAllowed = config.forwardAllApps || config.selectedApps.isEmpty() || config.selectedApps.contains(pkg)
        if (!isAllowed) return

        val notification = sbn.notification ?: return
        val extras = notification.extras ?: return

        val title = extras.getCharSequence(Notification.EXTRA_TITLE, "")?.toString() ?: ""
        val text = extras.getCharSequence(Notification.EXTRA_TEXT, "")?.toString()
            ?: extras.getCharSequence(Notification.EXTRA_BIG_TEXT, "")?.toString()
            ?: ""
        val subText = extras.getCharSequence(Notification.EXTRA_SUB_TEXT, "")?.toString() ?: ""

        // Skip empty notifications
        if (title.isBlank() && text.isBlank()) return

        // Hold wakelock so CPU stays awake during network call
        try {
            wakeLock?.acquire(6000L)
        } catch (_: Exception) {}

        val pm = applicationContext.packageManager
        val appName = try {
            val appInfo = pm.getApplicationInfo(pkg, 0)
            pm.getApplicationLabel(appInfo).toString()
        } catch (_: Exception) {
            pkg
        }

        AppLogRepository.getInstance().addLog(
            EventLogItem(
                type = LogEventType.NOTIFICATION_CAPTURED,
                title = "Notifikasi Masuk: $appName",
                details = "[$title] $text",
                success = true
            )
        )

        // Dispatch immediately!
        serviceScope.launch {
            try {
                WebhookDispatcher.dispatchNotification(
                    context = applicationContext,
                    appName = appName,
                    packageName = pkg,
                    title = title,
                    message = text,
                    subText = subText,
                    postTime = sbn.postTime,
                    notifKey = sbn.key ?: "",
                    notifId = sbn.id
                )
            } finally {
                try {
                    if (wakeLock?.isHeld == true) {
                        wakeLock?.release()
                    }
                } catch (_: Exception) {}
            }
        }
    }

    companion object {
        fun ensureRebind(context: Context) {
            try {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N) {
                    val comp = ComponentName(context, SFRNotificationListenerService::class.java)
                    NotificationListenerService.requestRebind(comp)
                }
            } catch (_: Exception) {}
        }
    }
}
